import test from 'node:test';
import assert from 'node:assert/strict';
import {STUDY_CONTEXT,isLocalLegislation,studyEligibility,eligibleForList} from '../study-context.mjs';
const exam={orgao:'CMVOTORANTIM'};
test('referência atual é Candeias do Jamari sem alterar os originais',()=>{
 assert.equal(STUDY_CONTEXT.municipality,'Candeias do Jamari');
 assert.equal(STUDY_CONTEXT.state,'RO');
});
test('questões comuns permanecem disponíveis para todos os municípios',()=>{
 const q={discipline:'Matemática',disciplineCode:'MA',stem:'Calcule 2 + 2.'};
 assert.equal(isLocalLegislation(q,exam),false);
 assert.equal(studyEligibility(q,exam,'candeias').allowed,true);
});
test('legislação institucional de outra Câmara aguarda validação jurídica',()=>{
 const q={discipline:'Legislação',disciplineCode:'LE',topic:'Legislação institucional',stem:'Segundo a Resolução 04 da Câmara Municipal de Votorantim...' };
 assert.equal(isLocalLegislation(q,exam),true);
 assert.equal(eligibleForList(q,exam,'candeias'),false);
 assert.equal(eligibleForList(q,exam,'original'),true);
});
test('nem a mera troca de localidade nem uma aprovação informal valem como adaptação',()=>{
 const q={discipline:'Legislação',disciplineCode:'LE',stem:'Câmara Municipal de Votorantim',adaptation:{target:STUDY_CONTEXT.id,approved:true}};
 assert.equal(studyEligibility(q,exam,'candeias').allowed,false);
});
test('adaptação verificada com fonte e gabarito pode ser considerada, preservando a questão original',()=>{
 const q={id:'adapted-1',originalQuestionId:'old-1',discipline:'Legislação',disciplineCode:'LE',stem:'Câmara Municipal de Candeias',
 answer:'A',adaptation:{target:STUDY_CONTEXT.id,approved:true,law:'Lei Orgânica',legalReason:'Dispositivo verificado.',sourceUrl:'https://legislacao.candeiasdojamari.ro.leg.br/',sourceArticle:'Art. 1º',verifiedAnswer:'A'}};
 assert.equal(studyEligibility(q,{orgao:'CMCJ'},'candeias').allowed,true);
});

test('questão oficial de Candeias é elegível sem fingir que foi adaptada',()=>{
 const q={discipline:'Legislação',disciplineCode:'LE',topic:'Legislação institucional',
  stem:'Segundo a Câmara Municipal de Candeias do Jamari, qual é o procedimento correto?'};
 assert.equal(studyEligibility(q,{orgao:'CMCJ'},'candeias').allowed,true);
});

test('adaptação automática com artigo e gabarito fica disponível, mas não aparece na versão original',()=>{
 const q={id:'cj-q-1',originalQuestionId:'q-1',answer:'C',discipline:'Legislação',disciplineCode:'LE',stem:'Concurso público de Candeias',options:[],
 adaptation:{target:STUDY_CONTEXT.id,autoGenerated:true,law:'Resolução nº 173/CMCJ/2025',legalReason:'Texto respaldado no art. 7º.',sourceUrl:'https://athus4.candeiasdojamari.ro.leg.br/',sourceArticle:'Art. 7º',verifiedAnswer:'C'}};
 assert.equal(studyEligibility(q,exam,'candeias').allowed,true);
 assert.equal(studyEligibility(q,exam,'original').allowed,false);
 assert.equal(studyEligibility({...q,answer:'A'},exam,'candeias').allowed,false);
});

test('FEPESE Brusque questão 20: lei complementar de outra cidade fica só na prova original',()=>{
 const fepe={id:'exam-fepe',orgao:'PM-BRUSQUE',banca:'FEPESE',title:'2026 — FEPESE — PM-BRUSQUE — Analista de Informática'};
 const q={
  originalNumber:20,
  discipline:'Legislação',disciplineCode:'LE',topic:'Geral',
  stem:'Com base na Lei Complementar Municipal de Brusque nº 143/2009 (Plano de Cargos e Carreiras), a promoção horizontal é a passagem do servidor estável. Para especialistas, será considerada a participação em cursos de formação continuada com carga horária mínima total de:',
  answer:'D',
  options:'ABCDE'.split('').map((letter,i)=>({letter,text:['15h','30h','60h','90h','120h'][i]}))
 };
 assert.equal(isLocalLegislation(q,fepe),true);
 assert.equal(studyEligibility(q,fepe,'candeias').allowed,false);
 assert.equal(eligibleForList(q,fepe,'candeias'),false);
 assert.equal(eligibleForList(q,fepe,'original'),true);
 assert.equal(studyEligibility(q,fepe,'candeias').status,'invalid-for-candeias');
});
test('citação incidental de lei municipal de cidade diferente não vira conteúdo de Candeias',()=>{
 const q={discipline:'Legislação',disciplineCode:'LE',
  stem:'Segundo a Lei Complementar Municipal de Brusque nº 143/2009, qual requisito vale para o servidor?'};
 const e={orgao:'PM-BRUSQUE',title:'2026 — FEPESE — PM-BRUSQUE'};
 assert.equal(studyEligibility(q,e,'candeias').allowed,false);
 assert.equal(studyEligibility(q,e,'original').allowed,true);
});
