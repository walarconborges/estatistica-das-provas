const norm=s=>String(s||'').normalize('NFD').replace(/[\u0300-\u036f]/g,'').toUpperCase();
export function isLegislationQuestion(q){
 return q?.disciplineCode==='LE'||/LEGISLACAO|DIREITO ADMINISTRATIVO|DIREITO CONSTITUCIONAL/.test(norm(q?.discipline));
}
export function isLocalLegislation(q,e){
 if(!isLegislationQuestion(q))return false;
 const text=norm([q.stem,q.topic,q.contextText,q.heading].join(' '));
 if(/LEGISLACAO INSTITUCIONAL|CAMARA MUNICIPAL|PREFEITURA MUNICIPAL|LEI ORGANICA|REGIMENTO INTERNO|RESOLUCAO N|PROCURADORIA DA CAMARA|DIRETORIA LEGISLATIVA|LEI (?:COMPLEMENTAR )?MUNICIPAL|PLANO DE CARGOS E CARREIRAS|REGIME JURIDICO (?:DOS )?SERVIDORES MUNICIPAIS/.test(text))return true;
 const org=norm(e?.orgao||q.orgao).replace(/[^A-Z0-9]/g,'');
 return /^CM/.test(org)&&/LEGISLACAO|SERVIDORES MUNICIPAIS|CARGOS DA CAMARA/.test(text);
}
/**
 * Não presume equivalência pela troca do nome da cidade.
 * Sem correspondência legal APROVADA, só aparece no banco original.
 */
export function studyEligibility(q,e,mode='candeias'){
 if(q?.originalQuestionId){
  if(mode==='original')return {allowed:false,status:'adapted-not-in-original'};
  const adaptation=q.adaptation||{};
  const complete=adaptation.target===STUDY_CONTEXT.id&&
   Boolean(adaptation.sourceUrl&&adaptation.sourceArticle&&adaptation.law&&adaptation.legalReason)&&
   adaptation.verifiedAnswer===q.answer&&/^[A-E]$/.test(q.answer||'');
  if(complete&&(adaptation.autoGenerated===true||adaptation.approved===true))
   return {allowed:true,status:adaptation.autoGenerated?'adapted-automatic':'adapted-approved'};
  return {allowed:false,status:'adaptation-incomplete'};
 }
 if(mode==='original'||!isLocalLegislation(q,e))return {allowed:true,status:'original'};
 // Questão original oficial do próprio município não é uma adaptação.
 const municipality=/CANDEIAS DO JAMARI|\bCMCJ\b/;
 const questionJurisdiction=norm([q.stem,q.contextText,q.heading].join(' '));
 const examJurisdiction=norm([e?.orgao,e?.title,q.orgao].join(' '));
 const clearlyOther=/BRUSQUE|VOTORANTIM|PORTO VELHO|ARIQUEMES|JI-PARANA/.test(questionJurisdiction);
 if(!clearlyOther&&(municipality.test(questionJurisdiction)||municipality.test(examJurisdiction)))
  return {allowed:true,status:'local-original'};

 return {allowed:false,status:'invalid-for-candeias',reason:'Sem correspondência legal verificada em Candeias do Jamari. A questão permanece disponível em sua versão original.'};
}
export function eligibleForList(q,e,mode){
 return studyEligibility(q,e,mode).allowed;
}
